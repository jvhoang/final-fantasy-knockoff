/**
 * Human-readable ability card for FFT-depth loadout UI.
 */
export function formatAbilityDetail(idOrAbility) {
  const a = typeof idOrAbility === 'string' ? ABILITIES[idOrAbility] : idOrAbility;
  if (!a) return null;
  const desc =
    a.description ||
    (a.name + ': ' + a.kind + ' power ' + a.power + ', MP ' + a.mpCost + ', range ' + a.minRange + '-' + a.maxRange + ', AoE ' + a.aoe + (a.aoeSize ? 'x' + a.aoeSize : '') + ', CT charge ' + a.castTime + ', effect ' + (a.effect || 'none') + '.');
  return {
    id: a.id,
    name: a.name,
    kind: a.kind,
    power: a.power,
    mpCost: a.mpCost,
    minRange: a.minRange,
    maxRange: a.maxRange,
    aoe: a.aoe,
    aoeSize: a.aoeSize,
    castTime: a.castTime,
    effect: a.effect || null,
    element: a.element || null,
    presentation: a.presentation || (a.castTime > 0 ? 'cast' : a.kind === 'physical' ? 'melee' : 'support'),
    description: desc,
    summary: 'MP ' + a.mpCost + ' · R' + a.minRange + '-' + a.maxRange + ' · ' + a.aoe + (a.aoeSize ? a.aoeSize : '') + ' · CT' + a.castTime + ' · Pwr ' + a.power,
  };
}

export function listAbilities() {
  return Object.values(ABILITIES).map((a) => formatAbilityDetail(a));
}

export function getAbility(id) {
  const a = ABILITIES[id];
  if (!a) throw new Error(`Unknown ability: ${id}`);
  return a;
}
